/**
 * Pulls content out of Sanity at BUILD time and writes it into
 * src/content/generated/. Nothing here runs in the browser — visitors never
 * talk to Sanity, so the site keeps exactly the runtime dependencies it has
 * today, which is none.
 *
 * Run automatically by `npm run build` (see the `prebuild` script).
 *
 * Fail-open by design:
 *   - Sanity unreachable  -> warn, keep the committed JSON, build succeeds.
 *   - Sanity returns junk -> fail the build loudly rather than ship it.
 *   - A page not yet in Sanity -> writes null; the component uses its
 *     built-in copy, so half-migrated is a safe state.
 *
 * The generated files are COMMITTED. That is deliberate: the site still
 * builds if the Sanity account lapses, `npm start` works with no network,
 * and every publish leaves a reviewable diff in git.
 */
import { writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_ID = "bj87pb9z";
const DATASET = "production";
const API_VERSION = "2024-01-01";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "src", "content", "generated");
const IMG_DIR = path.join(ROOT, "src", "assets", "generated");

/**
 * Images published in Sanity are DOWNLOADED here at build time and emitted as
 * real `import` statements, so webpack bundles them exactly like any other
 * asset: content-hashed filename, immutable cache header, served from the same
 * origin as the site. A visitor's browser never contacts Sanity.
 *
 * Sanity asset IDs are content hashes, so a filename only changes when the
 * picture does — an unchanged publish produces no git diff.
 */
const downloads = new Map(); // key -> { url, file }

function registerImage(url, width) {
  if (!url || !url.startsWith("http")) return url;
  const assetId = url.split("/").pop().split(".")[0];
  const key = `${assetId}-${width}`;
  downloads.set(key, {
    url: `${url}?w=${width}&fm=webp&q=78&fit=max`,
    file: `${key}.webp`,
  });
  return key; // the component resolves this through the generated image map
}

/**
 * Gallery photos are NOT baked. There can be dozens per event and hundreds
 * overall — committing those binaries would grow the repo without bound and
 * they cannot be removed from git history later. They sit below the fold and
 * load lazily, so a CDN round trip is the right trade. Cover photos and hero
 * banners stay baked because they are few, fixed, and above the fold.
 */
function cdnUrl(url, width) {
  if (!url || !url.startsWith("http")) return url;
  return `${url}?w=${width}&fm=webp&q=78&fit=max&auto=format`;
}

async function downloadImages() {
  if (downloads.size === 0) {
    await writeFile(
      path.join(OUT_DIR, "images.js"),
      "// No CMS images published yet.\nexport const IMAGES = {};\n",
    );
    return;
  }
  await mkdir(IMG_DIR, { recursive: true });

  let fetched = 0;
  for (const [key, { url, file }] of downloads) {
    const dest = path.join(IMG_DIR, file);
    if (existsSync(dest)) continue; // content-hashed: same name means same bytes
    const res = await fetch(url, { signal: AbortSignal.timeout(30000) });
    if (!res.ok) throw new Error(`image ${key}: HTTP ${res.status}`);
    await writeFile(dest, Buffer.from(await res.arrayBuffer()));
    fetched++;
  }

  const keys = [...downloads.keys()];
  const body =
    "// Generated by scripts/fetch-content.mjs — do not edit.\n" +
    "// Real imports, so webpack fingerprints and bundles these like any asset.\n" +
    keys.map((k, i) => `import i${i} from "../../assets/generated/${downloads.get(k).file}";`).join("\n") +
    "\n\nexport const IMAGES = {\n" +
    keys.map((k, i) => `  ${JSON.stringify(k)}: i${i},`).join("\n") +
    "\n};\n";
  await writeFile(path.join(OUT_DIR, "images.js"), body);
  console.log(`✓ Images: ${downloads.size} bundled (${fetched} newly downloaded)`);
}

