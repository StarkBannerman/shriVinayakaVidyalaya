// Deliberately the UNCACHED api host, not apicdn. This runs once per build,
// triggered by a publish webhook — a cached response would hand the build
// pre-publish content and silently deploy stale copy.
const endpoint = (query) =>
  `https://${PROJECT_ID}.api.sanity.io/v${API_VERSION}/data/query/${DATASET}` +
  `?query=${encodeURIComponent(query)}`;

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  let reachable = true;

  for (const src of SOURCES) {
    const out = path.join(OUT_DIR, src.file);

    let result;
    try {
      const res = await fetch(endpoint(src.query), {
        signal: AbortSignal.timeout(20000),
      });
      if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`);
      result = (await res.json()).result;
    } catch (err) {
      reachable = false;
      console.warn(`⚠  ${src.label}: could not reach Sanity (${err.message})`);
      if (!existsSync(out)) {
        await writeFile(out, JSON.stringify(src.empty, null, 2) + "\n");
      }
      continue;
    }

    src.check(result); // throws -> build fails, see catch below

    const count = Array.isArray(result.news)
      ? `${result.news.length} item(s)`
      : result.page
        ? "authored"
        : "not authored yet — using built-in copy";
    console.log(`✓ ${src.label}: ${count}`);

    await writeFile(out, JSON.stringify(result, null, 2) + "\n");
  }

  await downloadImages();

  if (!reachable) {
    console.warn("\n   Building with the last committed content.\n");
  }
}

main().catch((err) => {
  console.error(`\n✖ Content is invalid, refusing to build: ${err.message}\n`);
  process.exit(1);
});
